-- =====================================================================
-- RELATORIO 3 (AGREGACAO) - Media de ruido, luminosidade e lotacao por categoria
-- MongoDB: aggregate com $unwind + $group + $round
-- Esperado:
--   LAZER            2    1.67  2.67  3
--   MERCADO          4    3     4.67  3
--   SAUDE            2    1.75  2.25  8
--   SERVICO_PUBLICO  3    2     4     3
--   TRANSPORTE       4.67 3     5     3
-- =====================================================================
PROMPT RELATORIO 3 - Media sensorial por categoria (agregacao)
SELECT l.categoria,
       ROUND(AVG(a.ruido), 2)        AS media_ruido,
       ROUND(AVG(a.luminosidade), 2) AS media_luminosidade,
       ROUND(AVG(a.lotacao), 2)      AS media_lotacao,
       COUNT(*)                      AS qtd_avaliacoes
  FROM ser_avaliacao a
  JOIN ser_local l ON l.id = a.local_id
 GROUP BY l.categoria
 ORDER BY l.categoria;

