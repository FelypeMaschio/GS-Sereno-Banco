-- =====================================================================
-- 1. SER_USUARIO - cidadao ou gestor que usa o app
-- =====================================================================
CREATE TABLE ser_usuario (
    id                   NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    nome                 VARCHAR2(120) NOT NULL,
    email                VARCHAR2(150) NOT NULL,
    senha_hash           VARCHAR2(100) NOT NULL,            -- BCrypt tem 60 caracteres; folga para trocar o algoritmo
    papel                VARCHAR2(10)  DEFAULT ON NULL 'CIDADAO',
    modo_baixo_estimulo  NUMBER(1)     DEFAULT ON NULL 0,   -- 0/1 no lugar de BOOLEAN (compativel com versoes < 23)
    criado_em            TIMESTAMP     DEFAULT ON NULL SYSTIMESTAMP,
    CONSTRAINT pk_ser_usuario        PRIMARY KEY (id),
    CONSTRAINT uk_usuario_email      UNIQUE (email),
    CONSTRAINT ck_usuario_papel      CHECK (papel IN ('CIDADAO', 'GESTOR')),
    CONSTRAINT ck_usuario_baixo_est  CHECK (modo_baixo_estimulo IN (0, 1)),
    -- formato minimo de e-mail e sempre minusculo: impede "Ana@x.com" e "ana@x.com" como duas contas
    CONSTRAINT ck_usuario_email_fmt  CHECK (email LIKE '_%@_%._%' AND email = LOWER(email))
);

-- =====================================================================
-- 2. SER_LOCAL - lugar avaliado no mapa sensorial (Calmaria)
-- =====================================================================
CREATE TABLE ser_local (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR2(120) NOT NULL,
    categoria     VARCHAR2(20)  NOT NULL,
    endereco      VARCHAR2(200) NOT NULL,
    latitude      NUMBER(9,6)   NOT NULL,   -- 6 casas decimais ~ 11 cm de precisao
    longitude     NUMBER(9,6)   NOT NULL,
    indice_calma  NUMBER(3),                -- NULL = ainda sem avaliacoes (diferente de 0 = caotico)
    CONSTRAINT pk_ser_local          PRIMARY KEY (id),
    CONSTRAINT uk_local_nome_end     UNIQUE (nome, endereco),   -- evita o mesmo lugar cadastrado duas vezes
    CONSTRAINT ck_local_categoria    CHECK (categoria IN ('SAUDE', 'MERCADO', 'TRANSPORTE',
                                                          'LAZER', 'SERVICO_PUBLICO', 'EDUCACAO')),
    CONSTRAINT ck_local_latitude     CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT ck_local_longitude    CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_local_indice       CHECK (indice_calma BETWEEN 0 AND 100)
);

-- =====================================================================
-- 3. SER_AVALIACAO - nota sensorial de um usuario para um local
-- =====================================================================
CREATE TABLE ser_avaliacao (
    id                NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    local_id          NUMBER(19)    NOT NULL,
    usuario_id        NUMBER(19),               -- anulavel de proposito: anonimizacao LGPD (ver FK abaixo)
    ruido             NUMBER(1)     NOT NULL,   -- 1 = calmo ... 5 = muito intenso
    luminosidade      NUMBER(1)     NOT NULL,
    lotacao           NUMBER(1)     NOT NULL,
    data_hora_visita  TIMESTAMP     NOT NULL,   -- quando a pessoa ESTEVE la (base do "melhor horario")
    comentario        VARCHAR2(500),
    CONSTRAINT pk_ser_avaliacao      PRIMARY KEY (id),
    -- sem cascade: nao se apaga um local que tem historico de avaliacoes
    CONSTRAINT fk_aval_local         FOREIGN KEY (local_id)   REFERENCES ser_local (id),
    -- se o usuario pedir exclusao da conta, a avaliacao fica anonima em vez de sumir
    CONSTRAINT fk_aval_usuario       FOREIGN KEY (usuario_id) REFERENCES ser_usuario (id) ON DELETE SET NULL,
    CONSTRAINT ck_aval_ruido         CHECK (ruido        BETWEEN 1 AND 5),
    CONSTRAINT ck_aval_luminosidade  CHECK (luminosidade BETWEEN 1 AND 5),
    CONSTRAINT ck_aval_lotacao       CHECK (lotacao      BETWEEN 1 AND 5)
);

-- =====================================================================
-- 4. SER_ESTACAO - estacao de metro/trem (espelha o modelo da API .NET)
-- =====================================================================
CREATE TABLE ser_estacao (
    id         NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR2(120) NOT NULL,
    linha      VARCHAR2(60)  NOT NULL,   -- ex.: '1-Azul'. Simplificacao: estacao de baldeacao guarda as linhas no texto
    endereco   VARCHAR2(200) NOT NULL,
    latitude   NUMBER(9,6)   NOT NULL,
    longitude  NUMBER(9,6)   NOT NULL,
    CONSTRAINT pk_ser_estacao        PRIMARY KEY (id),
    CONSTRAINT uk_estacao_nome_linha UNIQUE (nome, linha),
    CONSTRAINT ck_estacao_latitude   CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT ck_estacao_longitude  CHECK (longitude BETWEEN -180 AND 180)
);

-- =====================================================================
-- 5. SER_EQUIPAMENTO - elevador, escada rolante, rampa ou plataforma
--    status_atual e uma redundancia CONTROLADA: e o ultimo status reportado,
--    mantido pelo gatilho trg_reporte_atualiza_status (etapa 4), para o app
--    nao precisar varrer todos os reportes a cada abertura da estacao.
-- =====================================================================
CREATE TABLE ser_equipamento (
    id             NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    estacao_id     NUMBER(19)    NOT NULL,
    tipo           VARCHAR2(20)  NOT NULL,
    localizacao    VARCHAR2(150) NOT NULL,   -- ex.: 'Acesso Rua Vergueiro -> plataforma sentido Jabaquara'
    status_atual   VARCHAR2(20)  DEFAULT ON NULL 'FUNCIONANDO',
    atualizado_em  TIMESTAMP     DEFAULT ON NULL SYSTIMESTAMP,
    CONSTRAINT pk_ser_equipamento    PRIMARY KEY (id),
    CONSTRAINT fk_equip_estacao      FOREIGN KEY (estacao_id) REFERENCES ser_estacao (id),
    CONSTRAINT ck_equip_tipo         CHECK (tipo IN ('ELEVADOR', 'ESCADA_ROLANTE', 'RAMPA', 'PLATAFORMA')),
    CONSTRAINT ck_equip_status       CHECK (status_atual IN ('FUNCIONANDO', 'PARADO', 'EM_MANUTENCAO'))
);

-- =====================================================================
-- 6. SER_REPORTE - cidadao informa o status de um equipamento
-- =====================================================================
CREATE TABLE ser_reporte (
    id              NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY,
    equipamento_id  NUMBER(19)    NOT NULL,
    usuario_id      NUMBER(19),               -- anulavel: mesma regra LGPD da avaliacao
    status          VARCHAR2(20)  NOT NULL,
    observacao      VARCHAR2(500),
    criado_em       TIMESTAMP     DEFAULT ON NULL SYSTIMESTAMP,
    CONSTRAINT pk_ser_reporte        PRIMARY KEY (id),
    CONSTRAINT fk_reporte_equip      FOREIGN KEY (equipamento_id) REFERENCES ser_equipamento (id),
    CONSTRAINT fk_reporte_usuario    FOREIGN KEY (usuario_id)     REFERENCES ser_usuario (id) ON DELETE SET NULL,
    CONSTRAINT ck_reporte_status     CHECK (status IN ('FUNCIONANDO', 'PARADO', 'EM_MANUTENCAO'))
);

-- =====================================================================
-- 7. SER_AUDITORIA - trilha de auditoria (preenchida pelo gatilho trg_aud_avaliacao)
--    SEM FK de proposito: o registro de auditoria precisa sobreviver
--    mesmo depois que a linha auditada for apagada.
-- =====================================================================
CREATE TABLE ser_auditoria (
    id               NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY,
    tabela           VARCHAR2(30)   NOT NULL,
    operacao         VARCHAR2(6)    NOT NULL,
    registro_id      NUMBER(19)     NOT NULL,
    valores_antigos  VARCHAR2(4000),          -- foto da linha ANTES (:OLD)
    valores_novos    VARCHAR2(4000),          -- foto da linha DEPOIS (:NEW)
    usuario_bd       VARCHAR2(128)  DEFAULT ON NULL SYS_CONTEXT('USERENV', 'SESSION_USER'),
    data_hora        TIMESTAMP      DEFAULT ON NULL SYSTIMESTAMP,
    CONSTRAINT pk_ser_auditoria      PRIMARY KEY (id),
    CONSTRAINT ck_aud_operacao       CHECK (operacao IN ('INSERT', 'UPDATE', 'DELETE')),
    -- a propria tabela documenta a regra do :OLD/:NEW:
    -- INSERT nao tem valor antigo; DELETE nao tem valor novo; UPDATE tem os dois
    CONSTRAINT ck_aud_coerencia      CHECK (
           (operacao = 'INSERT' AND valores_antigos IS NULL AND valores_novos IS NOT NULL)
        OR (operacao = 'DELETE' AND valores_novos   IS NULL AND valores_antigos IS NOT NULL)
        OR (operacao = 'UPDATE' AND valores_antigos IS NOT NULL AND valores_novos IS NOT NULL)
    )
);

-- =====================================================================
-- 8. INDICES
--    O Oracle cria indice sozinho para PK e UNIQUE, mas NAO para FK.
--    Sem indice na FK: JOINs lentos e bloqueio da tabela filha inteira
--    quando a mae sofre DELETE/UPDATE da chave.
--    Indices compostos comecando pela FK cobrem a FK E a consulta do negocio.
-- =====================================================================
-- cobre fk_aval_local + "avaliacoes do local por horario" (indice de calma, melhor horario)
CREATE INDEX idx_aval_local_data      ON ser_avaliacao   (local_id, data_hora_visita);
CREATE INDEX idx_aval_usuario         ON ser_avaliacao   (usuario_id);
-- cobre fk_equip_estacao + "equipamentos parados da estacao" (fn_equipamentos_parados, relatorio 2)
CREATE INDEX idx_equip_estacao_status ON ser_equipamento (estacao_id, status_atual);
-- cobre fk_reporte_equip + "historico de reportes do equipamento" (confiabilidade)
CREATE INDEX idx_reporte_equip_data   ON ser_reporte     (equipamento_id, criado_em);
CREATE INDEX idx_reporte_usuario      ON ser_reporte     (usuario_id);
-- relatorio 1 filtra por categoria
CREATE INDEX idx_local_categoria      ON ser_local       (categoria);
-- "linha do tempo" de um registro auditado
CREATE INDEX idx_aud_tabela_registro  ON ser_auditoria   (tabela, registro_id, data_hora);

