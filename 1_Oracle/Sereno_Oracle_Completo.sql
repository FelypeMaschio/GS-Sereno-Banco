-- =====================================================================
-- GATILHO 1 - TRILHA DE AUDITORIA DAS AVALIACOES
--   AFTER: so audita o que realmente foi gravado (se o INSERT falhar num
--          CHECK, nao fica auditoria de algo que nao existe).
--   FOR EACH ROW: uma linha de auditoria por avaliacao afetada.
--   :OLD = linha antes (NULL no INSERT) | :NEW = linha depois (NULL no DELETE)
--   Nao le SER_AVALIACAO (so usa :OLD/:NEW), entao nao ha mutating table.
-- =====================================================================
CREATE OR REPLACE TRIGGER trg_aud_avaliacao
AFTER INSERT OR UPDATE OR DELETE ON ser_avaliacao
FOR EACH ROW
DECLARE
    v_operacao VARCHAR2(6);
    v_id       NUMBER;
    v_antigos  VARCHAR2(4000);
    v_novos    VARCHAR2(4000);
BEGIN
    IF INSERTING THEN
        v_operacao := 'INSERT';
        v_id       := :NEW.id;
    ELSIF UPDATING THEN
        v_operacao := 'UPDATE';
        v_id       := :NEW.id;
    ELSE
        v_operacao := 'DELETE';
        v_id       := :OLD.id;
    END IF;

    -- foto ANTES (existe em UPDATE e DELETE)
    IF NOT INSERTING THEN
        v_antigos := 'local_id=' || :OLD.local_id ||
                     '; usuario_id=' || NVL(TO_CHAR(:OLD.usuario_id), 'NULL') ||
                     '; ruido=' || :OLD.ruido ||
                     '; luminosidade=' || :OLD.luminosidade ||
                     '; lotacao=' || :OLD.lotacao ||
                     '; data_hora_visita=' || TO_CHAR(:OLD.data_hora_visita, 'YYYY-MM-DD HH24:MI') ||
                     '; comentario=' || NVL(:OLD.comentario, 'NULL');
    END IF;

    -- foto DEPOIS (existe em INSERT e UPDATE)
    IF NOT DELETING THEN
        v_novos := 'local_id=' || :NEW.local_id ||
                   '; usuario_id=' || NVL(TO_CHAR(:NEW.usuario_id), 'NULL') ||
                   '; ruido=' || :NEW.ruido ||
                   '; luminosidade=' || :NEW.luminosidade ||
                   '; lotacao=' || :NEW.lotacao ||
                   '; data_hora_visita=' || TO_CHAR(:NEW.data_hora_visita, 'YYYY-MM-DD HH24:MI') ||
                   '; comentario=' || NVL(:NEW.comentario, 'NULL');
    END IF;

    -- usuario_bd e data_hora entram pelo DEFAULT da tabela
    INSERT INTO ser_auditoria (tabela, operacao, registro_id, valores_antigos, valores_novos)
    VALUES ('SER_AVALIACAO', v_operacao, v_id, v_antigos, v_novos);
END trg_aud_avaliacao;
/

