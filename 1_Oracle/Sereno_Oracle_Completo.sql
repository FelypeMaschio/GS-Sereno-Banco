--   AFTER INSERT em SER_REPORTE: o reporte ja foi gravado com sucesso,
--   entao o status do equipamento pode ser atualizado.
--   Atualiza OUTRA tabela (SER_EQUIPAMENTO) e so usa :NEW, sem consultar
--   SER_REPORTE -> nao sofre mutating table.
--   Vale para qualquer origem do INSERT: procedimento, API ou INSERT manual.
-- =====================================================================
CREATE OR REPLACE TRIGGER trg_reporte_atualiza_status
AFTER INSERT ON ser_reporte
FOR EACH ROW
BEGIN
    UPDATE ser_equipamento
       SET status_atual  = :NEW.status,
           atualizado_em = NVL(:NEW.criado_em, SYSTIMESTAMP)
     WHERE id = :NEW.equipamento_id;
END trg_reporte_atualiza_status;
