-- =====================================================================
-- BLOCO 2 - IF + LOOP: acessibilidade de cada estacao
--   100% funcionando         -> ACESSIVEL
--   50% ou mais funcionando  -> PARCIAL
--   menos de 50%             -> INACESSIVEL
--   sem equipamentos         -> SEM DADOS (evita divisao por zero)
--   Elevador fora de operacao gera um ALERTA extra (e o unico acesso
--   possivel para cadeirantes).
-- Esperado: Se PARCIAL | Paraiso PARCIAL | Luz INACESSIVEL |
--           Consolacao ACESSIVEL | Butanta ACESSIVEL
-- =====================================================================
DECLARE
    v_total          PLS_INTEGER;
    v_funcionando    PLS_INTEGER;
    v_elev_parado    PLS_INTEGER;
    v_percentual     NUMBER;
    v_classificacao  VARCHAR2(20);
BEGIN
    DBMS_OUTPUT.PUT_LINE('=== ACESSIBILIDADE DAS ESTACOES ===');

    FOR r_est IN (SELECT id, nome, linha FROM ser_estacao ORDER BY id) LOOP
        SELECT COUNT(*),
               SUM(CASE WHEN status_atual = 'FUNCIONANDO' THEN 1 ELSE 0 END),
               SUM(CASE WHEN tipo = 'ELEVADOR' AND status_atual <> 'FUNCIONANDO' THEN 1 ELSE 0 END)
          INTO v_total, v_funcionando, v_elev_parado
          FROM ser_equipamento
         WHERE estacao_id = r_est.id;

        IF v_total = 0 THEN
            v_classificacao := 'SEM DADOS';
            v_percentual    := NULL;
        ELSE
            v_percentual := ROUND(v_funcionando / v_total * 100);
            IF v_funcionando = v_total THEN
                v_classificacao := 'ACESSIVEL';
            ELSIF v_funcionando / v_total >= 0.5 THEN
                v_classificacao := 'PARCIAL';
            ELSE
                v_classificacao := 'INACESSIVEL';
            END IF;
        END IF;

        DBMS_OUTPUT.PUT_LINE(
            RPAD(r_est.nome, 12) || ' | ' || RPAD(r_est.linha, 20) ||
            ' | ' || NVL(TO_CHAR(v_funcionando), '0') || '/' || v_total || ' funcionando (' ||
            NVL(TO_CHAR(v_percentual), '-') || '%) -> ' || v_classificacao ||
            CASE WHEN v_elev_parado > 0 THEN '  [ALERTA: elevador fora de operacao]' END);
    END LOOP;
END;
/

