-- =====================================================================
-- 0. LIMPEZA - remove as tabelas se existirem, sem quebrar se nao existirem
--    * Ordem: filhas antes das maes (boa pratica, mesmo com CASCADE CONSTRAINTS)
--    * CASCADE CONSTRAINTS: derruba FKs de outras tabelas que apontem para esta
--    * PURGE: nao manda para a lixeira (evita lixo BIN$ e sequencias orfas)
--    * ORA-00942 (tabela nao existe) e ignorado; qualquer outro erro sobe
-- =====================================================================
DECLARE
    TYPE t_lista IS TABLE OF VARCHAR2(30);
    v_tabelas t_lista := t_lista(
        'SER_AUDITORIA', 'SER_REPORTE', 'SER_EQUIPAMENTO', 'SER_ESTACAO',
        'SER_AVALIACAO', 'SER_LOCAL', 'SER_USUARIO'
    );
BEGIN
    FOR i IN 1 .. v_tabelas.COUNT LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP TABLE ' || v_tabelas(i) || ' CASCADE CONSTRAINTS PURGE';
            DBMS_OUTPUT.PUT_LINE('Removida   : ' || v_tabelas(i));
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE = -942 THEN
                    DBMS_OUTPUT.PUT_LINE('Nao existia: ' || v_tabelas(i));
                ELSE
                    RAISE;
                END IF;
        END;
    END LOOP;
END;
