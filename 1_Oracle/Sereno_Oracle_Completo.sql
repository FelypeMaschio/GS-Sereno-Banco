    -- Publica e sem DML: a API Java chama com
    --   SELECT pkg_calmaria.fn_indice_calma(:id) FROM dual
    FUNCTION fn_indice_calma (p_local_id IN NUMBER) RETURN NUMBER;

    -- Valida, insere a avaliacao e recalcula o indice_calma do local.
    PROCEDURE prc_registrar_avaliacao (
        p_local_id         IN  NUMBER,
        p_usuario_id       IN  NUMBER,
        p_ruido            IN  NUMBER,
        p_luminosidade     IN  NUMBER,
        p_lotacao          IN  NUMBER,
        p_data_hora_visita IN  TIMESTAMP,
        p_comentario       IN  VARCHAR2,
        p_avaliacao_id     OUT NUMBER
    );

END pkg_calmaria;
/

CREATE OR REPLACE PACKAGE BODY pkg_calmaria AS

    -- ---------- privada: valida uma nota (so existe dentro do body) ----------
    PROCEDURE validar_nota (p_nome IN VARCHAR2, p_valor IN NUMBER) IS
    BEGIN
        IF p_valor IS NULL OR p_valor <> TRUNC(p_valor) OR p_valor NOT BETWEEN 1 AND 5 THEN
            RAISE_APPLICATION_ERROR(-20001,
                'Nota de ' || p_nome || ' invalida (' || NVL(TO_CHAR(p_valor), 'vazia') ||
                '). Use um numero inteiro de 1 (calmo) a 5 (intenso).');
        END IF;
    END validar_nota;

    -- ---------- FUNCAO 1 ----------
    FUNCTION fn_indice_calma (p_local_id IN NUMBER) RETURN NUMBER IS
        v_existe NUMBER;
        v_media  NUMBER;
    BEGIN
        -- COUNT(*) sempre retorna uma linha: nao depende de NO_DATA_FOUND
        -- (que, dentro de um SELECT, viraria NULL silencioso em vez de erro)
        SELECT COUNT(*) INTO v_existe FROM ser_local WHERE id = p_local_id;
        IF v_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Local ' || p_local_id || ' nao encontrado.');
        END IF;

        -- media das notas de todas as avaliacoes (AVG devolve NULL se nao houver nenhuma)
        SELECT AVG(ruido + luminosidade + lotacao) / 3
          INTO v_media
          FROM ser_avaliacao
         WHERE local_id = p_local_id;

        IF v_media IS NULL THEN
            RETURN NULL;   -- sem avaliacoes: "sem dados" e diferente de 0 (caotico)
        END IF;

        -- media 1 -> 100 (muito calmo) | media 5 -> 0 (muito agitado)
        RETURN ROUND(100 - (v_media - 1) * 25);
    END fn_indice_calma;

    -- ---------- PROCEDIMENTO 1 ----------
    PROCEDURE prc_registrar_avaliacao (
        p_local_id         IN  NUMBER,
        p_usuario_id       IN  NUMBER,
        p_ruido            IN  NUMBER,
        p_luminosidade     IN  NUMBER,
        p_lotacao          IN  NUMBER,
        p_data_hora_visita IN  TIMESTAMP,
        p_comentario       IN  VARCHAR2,
        p_avaliacao_id     OUT NUMBER
    ) IS
        v_existe NUMBER;
        -- CAST tira o fuso: compara relogio com relogio, sem depender do fuso da sessao
        v_agora  TIMESTAMP := CAST(SYSTIMESTAMP AS TIMESTAMP);
        v_data   TIMESTAMP := NVL(p_data_hora_visita, v_agora);
        v_indice NUMBER;
    BEGIN
        -- 1) notas
        validar_nota('ruido',        p_ruido);
        validar_nota('luminosidade', p_luminosidade);
        validar_nota('lotacao',      p_lotacao);

        -- 2) local
        SELECT COUNT(*) INTO v_existe FROM ser_local WHERE id = p_local_id;
        IF v_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Local ' || p_local_id || ' nao encontrado.');
        END IF;

        -- 3) usuario
        SELECT COUNT(*) INTO v_existe FROM ser_usuario WHERE id = p_usuario_id;
        IF v_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'Usuario ' || NVL(TO_CHAR(p_usuario_id), 'vazio') || ' nao encontrado.');
        END IF;

        -- 4) nao se avalia uma visita que ainda nao aconteceu
        --    (um CHECK nao pode usar SYSTIMESTAMP, por isso a regra fica aqui)
        IF v_data > v_agora THEN
            RAISE_APPLICATION_ERROR(-20004, 'A data da visita nao pode estar no futuro.');
        END IF;

        -- 5) grava (o gatilho trg_aud_avaliacao registra a auditoria)
        INSERT INTO ser_avaliacao (local_id, usuario_id, ruido, luminosidade, lotacao,
                                   data_hora_visita, comentario)
        VALUES (p_local_id, p_usuario_id, p_ruido, p_luminosidade, p_lotacao,
                v_data, p_comentario)
        RETURNING id INTO p_avaliacao_id;

        -- 6) recalcula o indice do local. Fica no procedimento, e nao num gatilho
        --    de SER_AVALIACAO, porque a funcao le SER_AVALIACAO (mutating table, ORA-04091).
        v_indice := fn_indice_calma(p_local_id);
        UPDATE ser_local SET indice_calma = v_indice WHERE id = p_local_id;
    END prc_registrar_avaliacao;

END pkg_calmaria;
