-- MongoDB: aggregate com $bucket pela hora da visita
-- Percepcao = media de (ruido + luz + lotacao) / 3  -> quanto MENOR, mais calmo
-- Esperado:
--    6 MANHA (06h-11h)  2.7   10
--   12 TARDE (12h-17h)  2.5    8   <- faixa mais calma
--   18 NOITE (18h-23h)  4.33   2
-- =====================================================================
PROMPT RELATORIO 4 (bonus) - Percepcao media por faixa de horario
SELECT faixa_inicio,
       CASE faixa_inicio WHEN 6 THEN 'MANHA (06h-11h)'
                         WHEN 12 THEN 'TARDE (12h-17h)'
                         ELSE 'NOITE (18h-23h)' END AS faixa,
       ROUND(AVG((ruido + luminosidade + lotacao) / 3), 2) AS percepcao_media,
       COUNT(*) AS qtd_avaliacoes
  FROM (SELECT a.*,
               CASE WHEN EXTRACT(HOUR FROM data_hora_visita) < 12 THEN 6
                    WHEN EXTRACT(HOUR FROM data_hora_visita) < 18 THEN 12
                    ELSE 18 END AS faixa_inicio
          FROM ser_avaliacao a)
 GROUP BY faixa_inicio
 ORDER BY faixa_inicio;

