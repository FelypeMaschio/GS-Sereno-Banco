CREATE OR REPLACE PACKAGE BODY pkg_acessibilidade AS

    -- ---------- FUNCAO 2 ----------
    FUNCTION fn_equipamentos_parados (p_estacao_id IN NUMBER) RETURN NUMBER IS
        v_existe NUMBER;
        v_qtd    NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_existe FROM ser_estacao WHERE id = p_estacao_id;
        IF v_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-20007, 'Estacao ' || p_estacao_id || ' nao encontrada.');
        END IF;

        SELECT COUNT(*)
          INTO v_qtd
          FROM ser_equipamento
         WHERE estacao_id = p_estacao_id
           AND status_atual IN ('PARADO', 'EM_MANUTENCAO');

        RETURN v_qtd;
    END fn_equipamentos_parados;

    -- ---------- PROCEDIMENTO 2 ----------
    PROCEDURE prc_registrar_reporte (
        p_equipamento_id IN  NUMBER,
        p_usuario_id     IN  NUMBER,
        p_status         IN  VARCHAR2,
        p_observacao     IN  VARCHAR2,
        p_reporte_id     OUT NUMBER
    ) IS
        v_existe NUMBER;
        v_status VARCHAR2(20) := UPPER(TRIM(p_status));   -- aceita ' parado ' -> 'PARADO'
    BEGIN
        -- 1) status
        IF v_status IS NULL OR v_status NOT IN ('FUNCIONANDO', 'PARADO', 'EM_MANUTENCAO') THEN
            RAISE_APPLICATION_ERROR(-20006,
                'Status "' || p_status || '" invalido. Use FUNCIONANDO, PARADO ou EM_MANUTENCAO.');
        END IF;

        -- 2) equipamento
        SELECT COUNT(*) INTO v_existe FROM ser_equipamento WHERE id = p_equipamento_id;
        IF v_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-20005, 'Equipamento ' || p_equipamento_id || ' nao encontrado.');
        END IF;

        -- 3) usuario
        SELECT COUNT(*) INTO v_existe FROM ser_usuario WHERE id = p_usuario_id;
        IF v_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'Usuario ' || NVL(TO_CHAR(p_usuario_id), 'vazio') || ' nao encontrado.');
        END IF;

        -- 4) grava; o gatilho AFTER INSERT atualiza o status do equipamento
        INSERT INTO ser_reporte (equipamento_id, usuario_id, status, observacao)
        VALUES (p_equipamento_id, p_usuario_id, v_status, p_observacao)
        RETURNING id INTO p_reporte_id;
    END prc_registrar_reporte;

    -- ---------- BONUS: Posso ir agora? ----------
    FUNCTION fn_posso_ir_agora (p_local_id IN NUMBER) RETURN VARCHAR2 IS
        v_nome     ser_local.nome%TYPE;
        v_lat      ser_local.latitude%TYPE;
        v_lon      ser_local.longitude%TYPE;
        v_indice   ser_local.indice_calma%TYPE;
        v_clima    VARCHAR2(40);
        v_est_id   ser_estacao.id%TYPE;
        v_est_nome ser_estacao.nome%TYPE;
        v_parados  NUMBER;
        v_existe   NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_existe FROM ser_local WHERE id = p_local_id;
        IF v_existe = 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Local ' || p_local_id || ' nao encontrado.');
        END IF;

        SELECT nome, latitude, longitude, indice_calma
          INTO v_nome, v_lat, v_lon, v_indice
          FROM ser_local
         WHERE id = p_local_id;

        v_clima := CASE
                       WHEN v_indice IS NULL THEN 'sem avaliacoes ainda'
                       WHEN v_indice >= 70   THEN 'CALMO (indice ' || v_indice || ')'
                       WHEN v_indice >= 40   THEN 'MODERADO (indice ' || v_indice || ')'
                       ELSE                       'AGITADO (indice ' || v_indice || ')'
                   END;

        -- estacao mais proxima: distancia aproximada em graus, com a longitude
        -- corrigida pelo cosseno da latitude (suficiente dentro de uma cidade)
        SELECT id, nome
          INTO v_est_id, v_est_nome
          FROM (SELECT id, nome
                  FROM ser_estacao
                 ORDER BY POWER(latitude - v_lat, 2)
                        + POWER((longitude - v_lon) * COS(v_lat * ACOS(-1) / 180), 2))
         WHERE ROWNUM = 1;

        v_parados := fn_equipamentos_parados(v_est_id);

        RETURN v_nome || ': ' || v_clima || ' | Estacao mais proxima: ' || v_est_nome ||
               CASE WHEN v_parados = 0
                    THEN ' com todos os equipamentos funcionando.'
                    ELSE ' com ' || v_parados || ' equipamento(s) fora de operacao.'
               END;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN   -- nenhuma estacao cadastrada
            RETURN v_nome || ': ' || v_clima || ' | Nenhuma estacao cadastrada.';
    END fn_posso_ir_agora;

END pkg_acessibilidade;
