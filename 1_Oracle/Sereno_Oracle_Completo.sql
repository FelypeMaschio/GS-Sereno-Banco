DECLARE
    CURSOR c_locais IS
        SELECT id, nome, categoria, indice_calma
          FROM ser_local
         ORDER BY indice_calma NULLS LAST, nome;

    v_local      c_locais%ROWTYPE;    -- registro com o mesmo formato da linha do cursor
    v_criticos   PLS_INTEGER := 0;
    v_sem_dados  PLS_INTEGER := 0;
    c_limite     CONSTANT PLS_INTEGER := 40;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=== LOCAIS CRITICOS (indice de calma < ' || c_limite || ') ===');

    OPEN c_locais;
    LOOP
        FETCH c_locais INTO v_local;
        EXIT WHEN c_locais%NOTFOUND;

        IF v_local.indice_calma IS NULL THEN
            v_sem_dados := v_sem_dados + 1;
        ELSIF v_local.indice_calma < c_limite THEN
            v_criticos := v_criticos + 1;
            DBMS_OUTPUT.PUT_LINE(
                RPAD(v_local.nome, 32) || ' | ' || RPAD(v_local.categoria, 15) ||
                ' | indice ' || LPAD(v_local.indice_calma, 3) ||
                ' | evite ir sem fone abafador');
        END IF;
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('Locais lidos pelo cursor: ' || c_locais%ROWCOUNT);
    CLOSE c_locais;

    DBMS_OUTPUT.PUT_LINE('Total de criticos: ' || v_criticos ||
                         ' | sem avaliacoes: ' || v_sem_dados);
END;
